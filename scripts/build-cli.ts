/**
 * Builds the `bmad-board` executable: the app (vite build) and the server in one file, per platform.
 *
 *   bun scripts/build-cli.ts                       this machine's platform
 *   bun scripts/build-cli.ts --all                 macOS and Linux, arm64 and x64
 *   bun scripts/build-cli.ts --target bun-linux-x64 [--target …] [--skip-app]
 *
 * Binaries land in release/ as bmad-board-<os>-<arch>.
 */
import { mkdir, readdir, rm, writeFile } from 'node:fs/promises';
import { join, relative, resolve } from 'node:path';

const ALL = ['bun-darwin-arm64', 'bun-darwin-x64', 'bun-linux-x64', 'bun-linux-arm64'];
const args = process.argv.slice(2);
const targets = args.includes('--all') ? ALL : args.flatMap((a, i) => (args[i - 1] === '--target' ? [a] : []));
const here = resolve(import.meta.dir, '..');
const dist = join(here, 'dist');
const out = join(here, 'release');
const entry = join(here, '.cli-entry.ts');

const run = async (cmd: string[]) => {
  const p = Bun.spawn(cmd, { cwd: here, stdout: 'inherit', stderr: 'inherit' });
  if ((await p.exited) !== 0) throw new Error(`${cmd.join(' ')} failed`);
};

if (!args.includes('--skip-app')) await run(['bun', 'run', 'build']);

// An entry that embeds every built file and hands the server a URL path → embedded file map.
const walk = async (dir: string): Promise<string[]> =>
  (await readdir(dir, { withFileTypes: true })).flatMap((e) => (e.isDirectory() ? [] : [join(dir, e.name)])).concat(
    ...(await Promise.all((await readdir(dir, { withFileTypes: true })).filter((e) => e.isDirectory()).map((e) => walk(join(dir, e.name))))),
  );
const files = await walk(dist);
if (!files.some((f) => f.endsWith('index.html'))) throw new Error('dist/index.html is missing; the app build failed');
const lines = files.map((f, i) => `import a${i} from ${JSON.stringify(`./${relative(here, f)}`)} with { type: 'file' };`);
const map = files.map((f, i) => `  ${JSON.stringify(`/${relative(dist, f).split('\\').join('/')}`)}: a${i},`);
await writeFile(entry, `// Generated by scripts/build-cli.ts\n${lines.join('\n')}\n(globalThis as { __BMAD_BOARD_ASSETS__?: Record<string, string> }).__BMAD_BOARD_ASSETS__ = {\n${map.join('\n')}\n};\nawait import('./server/cli.ts');\n`);

await mkdir(out, { recursive: true });
try {
  for (const target of targets.length ? targets : [`bun-${process.platform}-${process.arch}`]) {
    const name = `bmad-board-${target.replace(/^bun-/, '')}`;
    await run(['bun', 'build', '--compile', '--minify', `--target=${target}`, entry, '--outfile', join(out, name)]);
    console.log(`built release/${name}`);
  }
} finally {
  await rm(entry, { force: true });
}
